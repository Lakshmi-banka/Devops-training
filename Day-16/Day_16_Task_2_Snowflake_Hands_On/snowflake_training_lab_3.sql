SELECT
    COUNT(*) AS TOTAL_SALES,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,

    ROUND(
        SUM(
            QUANTITY * UNIT_PRICE *
            (1 - DISCOUNT_PERCENT / 100)
        ), 2
    ) AS TOTAL_REVENUE

FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
WHERE ORDER_STATUS = 'COMPLETED';


SELECT
    PRODUCT,
    CATEGORY,
    SUM(QUANTITY) AS TOTAL_QUANTITY,

    ROUND(
        SUM(
            QUANTITY * UNIT_PRICE *
            (1 - DISCOUNT_PERCENT / 100)
        ), 2
    ) AS TOTAL_REVENUE

FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
WHERE ORDER_STATUS = 'COMPLETED'

GROUP BY PRODUCT, CATEGORY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    C.CUSTOMER_NAME,
    C.CUSTOMER_TYPE,
    O.ORDER_ID,
    O.PRODUCT,
    O.CITY,
    O.QUANTITY,
    O.ORDER_STATUS

FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS C

INNER JOIN SALES_DB.SALES_STAGING.CLEAN_ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID

ORDER BY C.CUSTOMER_NAME;

SELECT
    C.CUSTOMER_TYPE,

    COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,

    SUM(O.QUANTITY) AS TOTAL_UNITS_SOLD,

    ROUND(
        SUM(
            O.QUANTITY * O.UNIT_PRICE *
            (1 - O.DISCOUNT_PERCENT / 100)
        ), 2
    ) AS TOTAL_REVENUE

FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS C

INNER JOIN SALES_DB.SALES_STAGING.CLEAN_ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID

WHERE O.ORDER_STATUS = 'COMPLETED'

GROUP BY C.CUSTOMER_TYPE

ORDER BY TOTAL_REVENUE DESC;

SELECT
    CITY,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(
        SUM(
            QUANTITY * UNIT_PRICE *
            (1 - DISCOUNT_PERCENT / 100)
        ), 2
    ) AS TOTAL_REVENUE
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
WHERE ORDER_STATUS = 'COMPLETED'
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    DATE_TRUNC('MONTH', ORDER_DATE) AS SALES_MONTH,
    ROUND(
        SUM(
            QUANTITY * UNIT_PRICE *
            (1 - DISCOUNT_PERCENT / 100)
        ), 2
    ) AS MONTHLY_REVENUE
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
WHERE ORDER_STATUS = 'COMPLETED'
GROUP BY DATE_TRUNC('MONTH', ORDER_DATE)
ORDER BY SALES_MONTH;

SELECT
    SALES_CHANNEL,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(
        SUM(
            QUANTITY * UNIT_PRICE *
            (1 - DISCOUNT_PERCENT / 100)
        ), 2
    ) AS TOTAL_REVENUE
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
WHERE ORDER_STATUS = 'COMPLETED'
GROUP BY SALES_CHANNEL
ORDER BY TOTAL_REVENUE DESC;

SELECT
    ORDER_STATUS,
    COUNT(*) AS TOTAL_ORDERS
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS
GROUP BY ORDER_STATUS;