CREATE OR REPLACE TABLE SALES_DB.SALES_STAGING.CLEAN_ORDERS AS

SELECT
    COALESCE(
        NULLIF(TRIM(ORDER_ID), ''),
        'UNKNOWN'
    ) AS ORDER_ID,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_ID), ''),
        'UNKNOWN'
    ) AS CUSTOMER_ID,

    ORDER_DATE,

    COALESCE(
        NULLIF(INITCAP(TRIM(CITY)), ''),
        'Unknown'
    ) AS CITY,

    COALESCE(
        NULLIF(INITCAP(TRIM(PRODUCT)), ''),
        'Unknown'
    ) AS PRODUCT,

    COALESCE(
        NULLIF(INITCAP(TRIM(CATEGORY)), ''),
        'Unknown'
    ) AS CATEGORY,

    COALESCE(QUANTITY, 0) AS QUANTITY,

    COALESCE(UNIT_PRICE, 0) AS UNIT_PRICE,

    COALESCE(DISCOUNT_PERCENT, 0) AS DISCOUNT_PERCENT,

    COALESCE(
        NULLIF(UPPER(TRIM(SALES_CHANNEL)), ''),
        'UNKNOWN'
    ) AS SALES_CHANNEL,

    COALESCE(
        NULLIF(UPPER(TRIM(ORDER_STATUS)), ''),
        'UNKNOWN'
    ) AS ORDER_STATUS

FROM SALES_DB.SALES_STAGING.ORDERS;

SELECT *
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS;


CREATE OR REPLACE TABLE SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS AS

SELECT
    COALESCE(
        NULLIF(TRIM(CUSTOMER_ID), ''),
        'UNKNOWN'
    ) AS CUSTOMER_ID,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_NAME), ''),
        'Unknown Customer'
    ) AS CUSTOMER_NAME,

    COALESCE(
        NULLIF(UPPER(TRIM(CUSTOMER_TYPE)), ''),
        'UNKNOWN'
    ) AS CUSTOMER_TYPE,

    COALESCE(
        NULLIF(LOWER(TRIM(EMAIL)), ''),
        'No Email'
    ) AS EMAIL,

    COALESCE(
        NULLIF(INITCAP(TRIM(CITY)), ''),
        'Unknown'
    ) AS CITY,

    COALESCE(
        NULLIF(TRIM(SEGMENT_NOTE), ''),
        'No Information'
    ) AS SEGMENT_NOTE

FROM SALES_DB.SALES_STAGING.CUSTOMERS;


SELECT *
FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS;

SELECT
    (SELECT COUNT(*)
     FROM SALES_DB.SALES_STAGING.ORDERS) AS ORDERS,

    (SELECT COUNT(*)
     FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS) AS CLEAN_ORDERS,

    (SELECT COUNT(*)
     FROM SALES_DB.SALES_STAGING.CUSTOMERS) AS CUSTOMERS,

    (SELECT COUNT(*)
     FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS) AS CLEAN_CUSTOMERS;


SELECT
    COUNT_IF(CITY = 'Unknown') AS MISSING_CITY,
    COUNT_IF(PRODUCT = 'Unknown') AS MISSING_PRODUCT,
    COUNT_IF(QUANTITY = 0) AS ZERO_QUANTITY,
    COUNT_IF(UNIT_PRICE = 0) AS ZERO_PRICE
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS;

SELECT
    COUNT_IF(CUSTOMER_NAME = 'Unknown Customer') AS MISSING_NAME,
    COUNT_IF(EMAIL = 'No Email') AS MISSING_EMAIL,
    COUNT_IF(SEGMENT_NOTE = 'No Information') AS MISSING_NOTES
FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS;

SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    O.CITY,
    O.PRODUCT,
    O.QUANTITY,
    O.UNIT_PRICE,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_TYPE,
    C.EMAIL
FROM SALES_DB.SALES_STAGING.CLEAN_ORDERS O

INNER JOIN SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS C
    ON O.CUSTOMER_ID = C.CUSTOMER_ID

ORDER BY O.ORDER_ID;


SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_TYPE,
    O.ORDER_ID,
    O.PRODUCT,
    O.ORDER_STATUS
FROM SALES_DB.SALES_STAGING.CLEAN_CUSTOMERS C

LEFT JOIN SALES_DB.SALES_STAGING.CLEAN_ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID

ORDER BY C.CUSTOMER_ID;

