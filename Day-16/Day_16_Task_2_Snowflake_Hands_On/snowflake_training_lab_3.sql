CREATE DATABASE IF NOT EXISTS SALES_DB;

CREATE SCHEMA IF NOT EXISTS SALES_DB.SALES_STAGING;

USE DATABASE SALES_DB;

USE SCHEMA SALES_DB.SALES_STAGING;

CREATE WAREHOUSE IF NOT EXISTS SALES_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SALES_WH;

CREATE OR REPLACE TABLE SALES_DB.SALES_STAGING.ORDERS (
    ORDER_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    ORDER_DATE DATE,
    CITY VARCHAR(50),
    PRODUCT VARCHAR(100),
    CATEGORY VARCHAR(50),
    QUANTITY NUMBER(10,2),
    UNIT_PRICE NUMBER(12,2),
    DISCOUNT_PERCENT NUMBER(5,2),
    SALES_CHANNEL VARCHAR(30),
    ORDER_STATUS VARCHAR(30)
);

CREATE OR REPLACE TABLE SALES_DB.SALES_STAGING.CUSTOMERS (
    CUSTOMER_ID VARCHAR(20),
    CUSTOMER_NAME VARCHAR(100),
    CUSTOMER_TYPE VARCHAR(30),
    EMAIL VARCHAR(100),
    CITY VARCHAR(50),
    SEGMENT_NOTE VARCHAR(100)
);

CREATE OR REPLACE FILE FORMAT
SALES_DB.SALES_STAGING.SALES_CSV_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = FALSE
NULL_IF = ('NULL');

